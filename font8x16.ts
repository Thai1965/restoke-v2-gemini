    export function drawText8x16(text: string, x: number, y: number, color: number): void {
        let currentX = x;
        for (let i = 0; i < text.length; i++) {
            let ch = text.charAt(i);
            let glyph = getGlyph(ch);

            if (glyph == null) { currentX += WIDTH + SPACING; continue; }

            for (let row = 0; row < HEIGHT; row++) {
                let rowData = glyph[row];
                for (let col = 0; col < WIDTH; col++) {
                    if ((rowData & (0x80 >> col)) != 0) {

                        // ปรับตรงนี้: ส่งค่าสีไปแปลงผ่านฟังก์ชันส่วนกลางก่อนส่งให้จอวาด
                        let correctColor = DisplayUtils.swapRGB(color);
                        RBTFT18.drawPixel(currentX + col, y + row, correctColor);

                    }
                }
            }
            currentX += WIDTH + SPACING;
            if (currentX >= 128) break;
        }
    }
